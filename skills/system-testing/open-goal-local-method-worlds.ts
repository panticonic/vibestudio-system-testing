export type LocalMethodKind =
  | "inspect-counts"
  | "compare-template"
  | "verify-ownership"
  | "confirm-state";
type Profile =
  | "fresh"
  | "retained"
  | "interrupted"
  | "refused"
  | "retained-refusal"
  | "no-grant"
  | "no-provider"
  | "moved";
export type LocalMethodWorld = ReturnType<typeof exchange>;
function exchange(
  id: string,
  split: "train" | "test",
  title: string,
  method: LocalMethodKind,
  profile: Profile,
  detail: string,
  goal: string,
) {
  return {
    id: "local-method-" + id,
    sourceGroup: "vibestudio:local-method:" + id,
    kind: "localMethodExchange",
    workspace: "system",
    split,
    title,
    method,
    profile,
    detail,
    goal,
  } as const;
}
